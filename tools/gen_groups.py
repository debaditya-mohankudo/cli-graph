"""Dev-time generator for the simple `mac` group modules (task:315f6563).

Reads local-mac's DOMAIN_MAP and each handler's signature, and writes one
mac/groups/<area>.py per area in AREAS. The output is committed; `mac` never
inspects handlers at runtime, because importing every handler module costs
about a second per call.

Run under local-mac's venv after a handler signature changes:
    ~/workspace/claude_for_mac_local/.venv/bin/python tools/gen_groups.py

Argument rules: a parameter without a default is positional; one with a default
is a --flag; bool flags are store_true; a Literal becomes choices; a dict
parameter takes a JSON string. A handler parameter named `limit` is fed from
the global --limit, so it is not added twice.
"""
import importlib
import inspect
import sys
import typing
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from mac.groups._backend import dispatcher  # noqa: E402

AREAS = ["time", "vpn", "podcasts", "music", "sound", "contacts",
         "calendar", "system", "market", "connector"]

# Verbs that change something. Reviewed by hand; everything else is read.
WRITE = {
    "time": {"alarm", "wait", "play_sound"},
    "vpn": {"connect", "disconnect", "pause"},
    "music": {"play", "pause", "next", "previous", "volume", "search_play",
              "play_playlist", "play_track"},
    "sound": {"set_output", "set_volume", "mute", "unmute"},
    "calendar": {"add_event", "delete_event"},
    "system": {"process_kill", "sleep_now", "sleep_in", "sleep_cancel",
               "sleep_winddown", "clipboard_write", "notify"},
    "connector": {"execute_action"},
}

HEADER = '''"""`mac {area}` — generated by tools/gen_groups.py from local-mac's {area}__* handlers. Do not edit."""
'''

KINDS = {bool: "bool", int: "int", float: "float", dict: "json"}


def kind(annotation):
    """(kind, choices): kind is 'bool' | 'int' | 'float' | 'json' | 'str'; choices only for a Literal."""
    if typing.get_origin(annotation) is typing.Literal:
        return "str", typing.get_args(annotation)
    for arg in typing.get_args(annotation) or (annotation,):  # `dict | None` -> dict
        base = typing.get_origin(arg) or arg
        if base in KINDS:
            return KINDS[base], None
    return "str", None


def parameters(fn):
    return inspect.signature(fn, eval_str=True).parameters.values()


def _first_line(fn):
    doc = (inspect.getdoc(fn) or "").split("\n")[0].strip().rstrip(".,")
    return doc[:1].lower() + doc[1:]


def _verb(area, action, fn):
    mode = "write" if action in WRITE.get(area, ()) else "read"
    arg_lines, call_args, uses_json = [], [], False
    for p in parameters(fn):
        if p.name == "limit":
            call_args.append(f"limit=ns.limit or {p.default!r}")
            continue
        k, choices = kind(p.annotation)
        required = p.default is inspect.Parameter.empty
        name = p.name if required else f"--{p.name.replace('_', '-')}"
        if k == "bool":
            opts = ['action="store_true"']
        else:
            opts = [] if required else [f"default={p.default!r}"]
            if k in ("int", "float"):
                opts.append(f"type={k}")
            elif k == "json":
                opts.append("type=json_object")
                uses_json = True
            if choices:
                opts.append(f"choices={choices!r}")
        arg_lines.append(f'p.add_argument({", ".join([repr(name)] + opts)})')
        call_args.append(f"{p.name}=ns.{p.name}")

    fname = f"{area}_{action}"
    lines = []
    if arg_lines:
        lines.append(f"    def {fname}_args(p):")
        lines += [f"        {a}" for a in arg_lines]
        lines.append("")
    args_kw = f", args={fname}_args" if arg_lines else ""
    lines.append(f'    @registry.verb("{area}", "{action}", mode="{mode}",')
    lines.append(f'                   desc={_first_line(fn)!r}{args_kw})')
    lines.append(f"    def {fname}(ns):")
    lines.append(f"        return call({', '.join([repr(area), repr(action)] + call_args)})")
    lines.append("")
    return lines, uses_json


def render(area, module_path, actions):
    module = importlib.import_module(module_path)
    body, uses_json = [], False
    for action in actions:
        lines, json_arg = _verb(area, action, getattr(module, f"handle_{action}"))
        body += lines
        uses_json |= json_arg
    imports = (["from mac.cli import json_object"] if uses_json else []) + \
        ["from mac.groups._backend import call"]
    return (HEADER.format(area=area) + "\n".join(imports) + "\n"
            + "\n\ndef register(registry):\n" + "\n".join(body).rstrip() + "\n")


def main():
    domain_map = dispatcher().DOMAIN_MAP
    for area in AREAS:
        module_path, actions = domain_map[area]
        unknown = WRITE.get(area, set()) - set(actions)
        if unknown:
            raise SystemExit(f"WRITE lists unknown {area} verbs: {sorted(unknown)}")
        out = REPO / "mac" / "groups" / f"{area}.py"
        out.write_text(render(area, module_path, actions))
        print(f"wrote {out.relative_to(REPO)} ({len(actions)} verbs)")


if __name__ == "__main__":
    main()
