"""Dev-time generator for the `mac` groups backed by separate MCP servers (task:25e053bc).

Starts each server in mac.groups._mcp_proxy.SERVERS, reads its tools/list and
writes mac/groups/<area>.py. The output is committed: `mac` never lists tools
at runtime, which would cost a server start on every `mac --help`.

    uv run python tools/gen_mcp_groups.py           # rewrite the modules
    uv run python tools/gen_mcp_groups.py --check   # exit 1 if any is stale

Argument rules follow tools/gen_groups.py, read from each tool's JSON schema
instead of a Python signature: a required property is positional, an optional
one is a --flag defaulting to argparse.SUPPRESS (so the server's own default
applies and none is copied here), a boolean is store_true, an enum becomes
choices, an object takes a JSON object, an array of objects a JSON list, an
array of scalars one or more values, and integer|string accepts either. Source
text properties listed in FILE_ARGS also get a --<name>-file PATH flag.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from mac.groups._mcp_proxy import SERVERS, list_tools  # noqa: E402

# One area per server in _mcp_proxy.SERVERS, named after it. Every tool the server lists becomes a verb.
AREAS = tuple(SERVERS)

# Verbs that change something. Reviewed by hand; everything else is read.
WRITE = {
    "wyckoff": {"plot_sr_chart", "db_init_state", "update_run", "update_delivery",
                "update_fno", "update_short_volume", "classify_announcements"},
}

# Properties that carry source text, so they can also be read from a file or stdin.
FILE_ARGS = {"sysml": ("code", "originalCode")}

MAX_DESC = 160

# Where a tool's first sentence makes a poor one-line description.
DESC = {
    ("sysml", "get_complexity"): "analyse structural complexity of a SysML model: complexity index, "
                                 "hotspots, coupling, documentation coverage",
    ("wyckoff", "classify_announcements"): "validate agent-labelled announcements for a tracked stock against "
                                           "the decision schema and insert the confident ones as news",
}

# Verbs whose result is passed through an _mcp_proxy function before it is returned.
POST = {("sysml", "preview"): "data_block"}

# Tools that return a list. FastMCP sends one text block per item, so a
# one-item list would otherwise come back as a lone object (see as_list).
# Checked against the handlers' return annotations by
# tests/test_parity_mcp_servers.py.
LIST_RESULT = {
    "astrology": {"aq_dasha_timeline", "aq_pd_timeline", "aq_planets", "aq_aspects_on_house",
                  "aq_strength_summary", "aq_bhava_chalit", "aq_vargottama", "aq_neecha_bhanga",
                  "aq_pushkar_navamsa", "aq_upcoming_transitions", "gochar_dasha_tally"},
}

HEADER = '''"""`mac {area}` — generated by tools/gen_mcp_groups.py from the {area} MCP server's tools/list. Do not edit."""
'''


def snake(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()


def flag(name):
    """The --flag for a schema property: definitionsOnly -> --definitions-only."""
    return "--" + snake(name).replace("_", "-")


def verb_name(area, tool):
    """astrology__d9 -> d9 in area astrology; panchang__today -> panchang_today; getSymbols -> get_symbols."""
    name = tool.removeprefix(f"{area}__").replace("__", "_").replace("-", "_")
    return snake(name)


def describe(area, verb, tool):
    if (area, verb) in DESC:
        return DESC[(area, verb)]
    paragraph = (tool.description or "").strip().split("\n\n")[0]
    text = " ".join(paragraph.split())  # docstrings wrap mid-sentence
    first = re.split(r"(?<=[.;])\s| -- ", text)[0].strip().rstrip(".,;")
    if len(first) > MAX_DESC:
        first = first[:MAX_DESC].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return first[:1].lower() + first[1:]


def kind(prop):
    """(kind, choices) for one JSON-schema property."""
    variants = [v for v in prop.get("anyOf", [prop]) if v.get("type") != "null"]
    types = {v.get("type") for v in variants}
    if types == {"integer", "string"}:
        return "int_or_str", None
    if len(variants) != 1:
        raise SystemExit(f"unsupported schema: {prop!r}")
    v = variants[0]
    t = v.get("type")
    if "enum" in v:
        return "str", tuple(v["enum"])
    if t == "array":
        item = v.get("items", {}).get("type")
        return {"object": "json_list", "integer": "list_int"}.get(item, "list_str"), None
    simple = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "json"}
    if t not in simple:
        raise SystemExit(f"unsupported schema type {t!r}: {prop!r}")
    return simple[t], None


TYPES = {"int": "type=int", "float": "type=float", "json": "type=json_object",
         "json_list": "type=json_list", "int_or_str": "type=int_or_str"}


def _verb(area, tool):
    """(verb, code lines, names the module must import) for one tool."""
    verb = verb_name(area, tool.name)
    mode = "write" if verb in WRITE.get(area, ()) else "read"
    schema = tool.inputSchema or {}
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    file_args = [n for n in FILE_ARGS.get(area, ()) if n in props]
    arg_lines, imports = [], {("_mcp_proxy", "call_tool")}
    for name, prop in props.items():
        if name == "limit":
            raise SystemExit(f"{tool.name}: a `limit` property would clash with mac's global --limit")
        k, choices = kind(prop)
        positional = name in required and name not in file_args
        opts = [] if positional else ["dest=" + repr(name), "default=argparse.SUPPRESS"]
        if k == "bool":
            if prop.get("default") is True:
                raise SystemExit(f"{tool.name}.{name}: a boolean defaulting to true cannot be a store_true flag")
            opts.append('action="store_true"')
        else:
            if k in ("list_str", "list_int"):
                opts.append('nargs="+"')
                if k == "list_int":
                    opts.append("type=int")
            elif k in TYPES:
                opts.append(TYPES[k])
                if k not in ("int", "float"):
                    imports.add(("cli", TYPES[k].removeprefix("type=")))
            if choices:
                opts.append(f"choices={choices!r}")
        if not positional:
            imports.add(("argparse", None))
        arg_lines.append(f"p.add_argument({', '.join([repr(name if positional else flag(name))] + opts)})")
        if name in file_args:
            arg_lines.append(f"p.add_argument({flag(name) + '-file'!r}, dest={f'{name}_file'!r}, "
                             f"default=None, metavar='PATH', help='read {name} from PATH (- for stdin)')")

    fname = f"{area}_{verb}"
    lines = []
    if arg_lines:
        lines.append(f"    def {fname}_args(p):")
        lines += [f"        {a}" for a in arg_lines]
        lines.append("")
    args_kw = f", args={fname}_args" if arg_lines else ""
    lines.append(f'    @registry.verb("{area}", "{verb}", mode="{mode}",')
    lines.append(f"                   desc={describe(area, verb, tool)!r}{args_kw})")
    lines.append(f"    def {fname}(ns):")
    if file_args:
        must = tuple(n for n in file_args if n in required)
        flags = {n: flag(n) for n in file_args}
        lines.append(f"        code_from(ns, {flags!r}" + (f", required={must!r}" if must else "") + ")")
        imports.add(("_mcp_proxy", "code_from"))
    given = ""
    if props:
        given = f", **given(ns, {tuple(props)!r})"
        imports.add(("_backend", "given"))
    call = f"call_tool({area!r}, {tool.name!r}{given})"
    post = "as_list" if verb in LIST_RESULT.get(area, ()) else POST.get((area, verb))
    if post:
        call = f"{post}({call})"
        imports.add(("_mcp_proxy", post))
    lines.append(f"        return {call}")
    lines.append("")
    return verb, lines, imports


def render(area, tools):
    body, needed, seen = [], set(), {}
    for tool in sorted(tools, key=lambda t: t.name):
        verb, lines, imports = _verb(area, tool)
        if verb in seen:
            raise SystemExit(f"{area}: {tool.name} and {seen[verb]} both map to verb {verb!r}")
        seen[verb] = tool.name
        body += lines
        needed |= imports

    def names(module):
        return ", ".join(sorted(n for m, n in needed if m == module))

    imports = (["import argparse", ""] if ("argparse", None) in needed else []) + \
        [f"from {path} import {names(module)}"
         for module, path in (("cli", "mac.cli"), ("_backend", "mac.groups._backend"),
                              ("_mcp_proxy", "mac.groups._mcp_proxy"))
         if names(module)]
    return (HEADER.format(area=area) + "\n".join(imports) + "\n"
            + "\n\ndef register(registry):\n" + "\n".join(body).rstrip() + "\n")


def module_path(area):
    return REPO / "mac" / "groups" / f"{area}.py"


def main(argv):
    check = "--check" in argv
    stale = []
    for area in AREAS:
        tools = list_tools(area)
        verbs = {verb_name(area, t.name) for t in tools}
        for table, entries in (("WRITE", WRITE), ("LIST_RESULT", LIST_RESULT)):
            unknown = entries.get(area, set()) - verbs
            if unknown:
                raise SystemExit(f"{table} lists unknown {area} verbs: {sorted(unknown)}")
        text = render(area, tools)
        out = module_path(area)
        if check:
            if not out.exists() or out.read_text() != text:
                stale.append(str(out.relative_to(REPO)))
            continue
        out.write_text(text)
        print(f"wrote {out.relative_to(REPO)} ({len(tools)} verbs)")
    if stale:
        print("stale (run tools/gen_mcp_groups.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
